from django.test import SimpleTestCase
from parameterized import parameterized
from pydantic import ValidationError as PydanticValidationError

from contact.schemas import ContactCreateSchema, ContactFilterSchema, ContactUpdateSchema


class ContactSchemaTest(SimpleTestCase):
    """ The type rules of a contact are not here: they read the record, so they
    belong to `ContactService.validate_data`. """

    @parameterized.expand(
        [
            ("email malformed", {"last_name": "Touque", "email": "not-an-email"}, "email"),
            ("birth date not a date", {"last_name": "Touque", "birth_date": "third age"}, "birth_date"),
            ("company too long for a ulid", {"last_name": "Touque", "parent": "0" * 27}, "parent"),
        ]
    )
    def test_create_schema_invalid(self, label, payload, field):
        with self.assertRaises(PydanticValidationError) as ctx:
            ContactCreateSchema(**payload)

        self.assertEqual([error["loc"][0] for error in ctx.exception.errors()], [field])

    @parameterized.expand([("email malformed", {"email": "not-an-email"}, "email")])
    def test_update_schema_invalid(self, label, payload, field):
        with self.assertRaises(PydanticValidationError) as ctx:
            ContactUpdateSchema(**payload)

        self.assertEqual([error["loc"][0] for error in ctx.exception.errors()], [field])

    @parameterized.expand(
        [
            # `ULID` rather than `str`: a malformed id is refused instead of
            # silently matching nothing.
            ("company not a ulid", {"parent": "the-pony"}, "parent"),
            ("tag not a ulid", {"tag": "hobbit"}, "tag"),
        ]
    )
    def test_filter_schema_invalid(self, label, payload, field):
        with self.assertRaises(PydanticValidationError) as ctx:
            ContactFilterSchema(**payload)

        self.assertEqual([error["loc"][0] for error in ctx.exception.errors()], [field])

    @parameterized.expand([(ContactCreateSchema,), (ContactUpdateSchema,)])
    def test_display_name_is_on_no_write_schema(self, schema):
        # Generated by the database from the names.
        self.assertNotIn("display_name", schema.model_fields)
